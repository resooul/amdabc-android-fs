"""Generate src/amdabc_fs/optim/paper_mpa.py from the authors' mealpy MPA.py.

The authors' OriginalMPA follows the published MATLAB code (Faramarzi et al.
2020, github.com/afshinfaramarzi/Marine-Predators-Algorithm): FADs/eddy step and
the phase step are evaluated separately, each followed by marine-memory
(greedy) selection, i.e. two evaluations per agent per iteration. Stock mealpy
3.0.3 merges the two steps into one evaluation.

One PATCH: in the phase step the archived code wrote the new fitness into the
agent object created for the FADs position, so the agent kept the FADs
solution with the phase fitness (solution/fitness mismatch). The patch creates
a new agent for the phase position.

Usage: python tools/port_paper_mpa.py /path/to/mealpy/swarm_based/MPA.py
"""
import ast, hashlib, sys
from pathlib import Path

SOURCE_SHA1 = "7aff47f56caefb848fbe75b0cc40f95589088efc"
OLD = """            if self.mode not in self.AVAILABLE_MODES:
                agent.target = self.get_target(pos_new)
                self.pop[idx] = self.get_better_agent(self.pop[idx], agent, self.problem.minmax)
"""
NEW = """            if self.mode not in self.AVAILABLE_MODES:
                # PATCH pairing: new agent for the phase position (the archived code
                # reused the FADs agent, mixing one position with another's fitness).
                agent = self.generate_empty_agent(pos_new)
                agent.target = self.get_target(pos_new)
                self.pop[idx] = self.get_better_agent(self.pop[idx], agent, self.problem.minmax)
"""


def main(src_path, out_path="src/amdabc_fs/optim/paper_mpa.py"):
    raw = Path(src_path).read_bytes()
    sha = hashlib.sha1(raw).hexdigest()
    if sha != SOURCE_SHA1:
        sys.exit(f"source SHA-1 {sha} != expected {SOURCE_SHA1}")
    src = raw.decode("utf-8"); lines = src.splitlines()
    node = next(n for n in ast.parse(src).body if isinstance(n, ast.ClassDef) and n.name == "OriginalMPA")
    body = "\n".join(lines[node.lineno - 1:node.end_lineno]) + "\n"
    if body.count(OLD) != 1:
        sys.exit("pairing patch did not match exactly once")
    body = body.replace(OLD, NEW)
    head = ('"""OriginalMPA as used in the paper, ported from the authors\' mealpy MPA.py.\n\n'
            f'GENERATED by tools/port_paper_mpa.py from source SHA-1 {sha}. Do not edit;\n'
            'see the generator for the single PATCH.\n"""\nimport numpy as np\n'
            'from .mealpy_core.optimizer import Optimizer\n\n\n')
    Path(out_path).write_text(head + body + "\n\nMPA = OriginalMPA\n", encoding="utf-8")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:])
