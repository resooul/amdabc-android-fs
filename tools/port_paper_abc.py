"""Generate src/amdabc_fs/optim/paper_abc.py from the authors' mealpy ABC.py.

The classes used in the paper are copied verbatim from the authors' modified
mealpy file; only the patches listed in PATCHES are applied. Each patch must
match exactly the expected number of times, so a changed source fails loudly.

Usage:
    python tools/port_paper_abc.py /path/to/mealpy/swarm_based/ABC.py
"""
from __future__ import annotations

import ast
import hashlib
import sys
from pathlib import Path

SOURCE_SHA1 = "8b9e1af61f27e2ce7a934db06561deb425b95b90"

# class in source -> name used in the paper
CLASSES = {
    "MD3ABC": "AMDABC",
    "MD31ABC": "AMDABC1",
    "MD32ABC": "AMDABC2",
    "MD33ABC": "AMDABC3",
    "OriginalABC2": "ABC",
    "GBestGuidedABC2": "GBABC",
    "GBC": "GBC",
    "ABCX": "ABCX",
    "DirectedABC": "DABC",
    "ABCVSS": "ABCVSS",
}

RESTART_OLD = """                for idx2 in range(0, self.NS):
                    self.pop[idx] = self.generate_agent()
                    self.trials[idx] = 0
"""
RESTART_NEW = """                for idx2 in range(0, self.NS):
                    # PATCH restart: the archived code wrote self.pop[idx] (the best
                    # slot) NS times, so the whole-population restart never happened.
                    j = idx if self.legacy_restart else idx2
                    self.pop[j] = self.generate_agent()
                    self.trials[j] = 0
"""

# (class, old, new, expected count)
PATCHES = [
    ("MD3ABC", RESTART_OLD, RESTART_NEW, 1),
    ("MD33ABC", RESTART_OLD, RESTART_NEW, 1),
    # PATCH schedule: alpha follows FE progress when a FE budget is active.
    ("MD3ABC", "(epoch / self.epoch)", "self._progress(epoch)", 1),
    ("MD31ABC", "(epoch / self.epoch)", "self._progress(epoch)", 1),
]

HEADER = '''"""ABC classes used in the paper, ported from the authors' mealpy ABC.py.

GENERATED by tools/port_paper_abc.py from source SHA-1 {sha}. Do not edit by
hand; change the generator instead. Class bodies are verbatim except for the
patches marked "PATCH" (see tools/port_paper_abc.py).

Paper names: {names}
"""
import numpy as np
from .mealpy_core.optimizer import Optimizer


class PaperOptimizer(Optimizer):
    """Base for the ported classes.

    legacy_restart : reproduce the archived restart bug (default False).
    """
    legacy_restart = False

    def _progress(self, epoch):
        """Search progress in [0, 1]: FE-based under a FE budget, else epoch-based."""
        prog = getattr(self.problem, "progress", None)
        return prog() if callable(prog) else epoch / self.epoch

'''


def main(src_path: str, out_path: str = "src/amdabc_fs/optim/paper_abc.py") -> None:
    raw = Path(src_path).read_bytes()
    sha = hashlib.sha1(raw).hexdigest()
    if sha != SOURCE_SHA1:
        sys.exit(f"source SHA-1 {sha} != expected {SOURCE_SHA1}")
    src = raw.decode("utf-8")
    lines = src.splitlines()
    tree = ast.parse(src)
    bodies = {}
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name in CLASSES:
            bodies[node.name] = "\n".join(lines[node.lineno - 1:node.end_lineno]) + "\n"
    missing = set(CLASSES) - set(bodies)
    if missing:
        sys.exit(f"classes not found: {sorted(missing)}")

    for cls, old, new, n in PATCHES:
        found = bodies[cls].count(old)
        if found != n:
            sys.exit(f"patch on {cls}: expected {n} match(es), found {found}")
        bodies[cls] = bodies[cls].replace(old, new)
    for cls in bodies:
        head = f"class {cls}(Optimizer):"
        if not bodies[cls].startswith(head):
            sys.exit(f"{cls}: unexpected class header")
        bodies[cls] = bodies[cls].replace(head, f"class {cls}(PaperOptimizer):", 1)

    names = ", ".join(f"{p} = {c}" for c, p in CLASSES.items())
    out = HEADER.format(sha=sha, names=names)
    out += "\n\n".join(bodies[c] for c in CLASSES)
    out += "\n\n# paper names\n" + "\n".join(f"{p} = {c}" for c, p in CLASSES.items() if p != c) + "\n"
    Path(out_path).write_text(out, encoding="utf-8")
    print(f"wrote {out_path} ({len(CLASSES)} classes, {len(PATCHES)} patches)")


if __name__ == "__main__":
    main(*sys.argv[1:])
